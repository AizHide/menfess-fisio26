create table if not exists public.menfess_messages (
  id bigint generated by default as identity primary key,
  "to" text not null,
  "from" text default '',
  message text not null check (char_length(message) <= 160),
  song text default '',
  created_at timestamptz not null default now()
);
alter table public.menfess_messages enable row level security;
-- The table is accessed only by Netlify Functions using the server-side service role key.
-- Do not expose SUPABASE_SERVICE_ROLE_KEY in the website's HTML or client-side code.
